import argparse
import json
import math
import random
import sys
from pathlib import Path
sys.dont_write_bytecode = True
from dynamic_reference import dynamic, packed, flatten
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from w4a8_reference import reference, error_metrics

ROOT = Path(__file__).resolve().parents[2]
MIN32, MAX32 = -(1 << 31), (1 << 31)-1
LUT = [math.floor(65536/(1+math.exp(-i/16))+0.5) for i in range(129)]

def rounded(v, shift=16):
    q = (abs(v)+(1 << (shift-1))) >> shift
    q = -q if v < 0 else q
    return max(MIN32, min(MAX32, q)), int(q < MIN32 or q > MAX32)

def element(gate, up):
    a = abs(gate)
    if a >= 8*65536:
        sigmoid = 0 if gate < 0 else 65536
    else:
        index, frac = divmod(a, 4096)
        s = LUT[index] + ((LUT[index+1]-LUT[index])*frac+2048)//4096
        sigmoid = 65536-s if gate < 0 else s
    silu, s1 = rounded(gate*sigmoid)
    product, s2 = rounded(silu*up)
    return dict(silu=silu, product=product, saturated=s1 | s2, sigmoid=sigmoid)

def exact_silu(x):
    return x/(1+math.exp(-x)) if x >= 0 else x*math.exp(x)/(1+math.exp(x))

def lut_source():
    lines = ['// Generated by ffn_reference.py --emit-lut; packed adjacent sigmoid samples.',
             'module silu_sigmoid_lut(input logic clk,en,input logic [6:0] address,output logic [33:0] data);',
             '    (* rom_style="block" *) logic [33:0] rom [0:127];', '    initial begin']
    for i in range(128):
        lines.append(f"        rom[{i}]=34'h{(LUT[i+1]<<17)|LUT[i]:09x};")
    lines += ['    end', '    always_ff @(posedge clk) if(en) data<=rom[address];', 'endmodule', '']
    return '\n'.join(lines)

def unit_cases():
    rng = random.Random(20261014)
    pairs = [(x,u) for x in (MIN32,MAX32,-524289,-524288,-524287,-65536,-1,0,1,65536,524287,524288,524289)
             for u in (MIN32,MAX32,-65536,-1,0,1,65536)]
    # Every segment seam, both signs, interpolation interiors, signed ties and tails.
    pairs += [(sign*(i*4096+delta), rng.randint(-500000,500000))
              for i in range(129) for delta in (-1,0,1,2047,2048,4095) for sign in (-1,1)
              if 0 <= i*4096+delta <= 524288]
    pairs += [(65536,32768),(65536,-32768),(-65536,32768),(-65536,-32768),
              (-1,65536),(MAX32,MAX32),(MIN32,MIN32),
              (1073741824,-131072),(1073741825,-131072),(MAX32,65536),(MAX32,65537)]
    pairs += [(rng.randint(MIN32,MAX32), rng.randint(MIN32,MAX32)) for _ in range(250)]
    return [dict(gate=g,up=u,**element(g,u)) for g,u in pairs]

def ffn_cases(group):
    g1 = 12 if group == 32 else 32
    rng = random.Random(20261014+group)
    cases = []
    for cid,(m,k,h,n,kind) in enumerate([(1,19,37,5,'normal'),(3,35,29,7,'normal'),
            (5,23,61,6,'normal'),(2,13,25,3,'zero'),(1,9,33,4,'saturated')]):
        ng1,ng2 = (k+g1-1)//g1,(h+group-1)//group
        a = [[rng.randint(-16,16) for _ in range(k)] for _ in range(m)]
        wg = [[rng.randint(-8,7) for _ in range(h)] for _ in range(k)]
        wu = [[rng.randint(-8,7) for _ in range(h)] for _ in range(k)]
        sx = [[rng.choice([256,512,900]) for _ in range(ng1)] for _ in range(m)]
        sg = [[rng.choice([201,501,900])+g for _ in range(h)] for g in range(ng1)]
        su = [[rng.choice([301,701,1100])+g for _ in range(h)] for g in range(ng1)]
        if kind == 'zero': a = [[0]*k for _ in range(m)]
        if kind == 'saturated':
            a = [[127]*k for _ in range(m)]
            wg = [[7 if c%2 == 0 else -8 for c in range(h)] for _ in range(k)]
            wu = [[7]*h for _ in range(k)]
            sx = [[65535]*ng1 for _ in range(m)]
            sg = su = [[65535]*h for _ in range(ng1)]
        gate,pg,rawg = reference(a,wg,sx,sg,g1)
        up,pu,rawu = reference(a,wu,sx,su,g1)
        e = [element(g,u) for g,u in zip(gate,up)]
        products = [x['product'] for x in e]
        q,s,clips,sats,absmax = [],[],[],[],[]
        for r in range(m):
            for g in range(ng2):
                d = dynamic(products[r*h+g*group:r*h+min(h,(g+1)*group)])
                q += d['q']; s.append(d['scale']); clips.append(d['scale_clipped'])
                sats += d['sat']; absmax.append(d['absmax'])
        wd = [[rng.randint(-8,7) for _ in range(n)] for _ in range(h)]
        sd = [[rng.choice([301,700,1300])+g*13+c for c in range(n)] for g in range(ng2)]
        y,pd,rawd = reference([q[r*h:(r+1)*h] for r in range(m)],wd,
                              [s[r*ng2:(r+1)*ng2] for r in range(m)],sd,group)
        idealp = [exact_silu(g/2**24)*(u/2**24) for g,u in zip(rawg,rawu)]
        idealy = [sum(idealp[r*h+i]*wd[i][c]*sd[i//group][c]/4096 for i in range(h))
                  for r in range(m) for c in range(n)]
        cases.append(dict(id=cid,kind=kind,m=m,k=k,h=h,n=n,ng1=ng1,ng2=ng2,
            a=flatten(a),wg=packed(wg),wu=packed(wu),sx=flatten(sx),sg=flatten(sg),su=flatten(su),
            gate=gate,up=up,pg=flatten([flatten(row) for row in pg]),pu=flatten([flatten(row) for row in pu]),
            silu=[x['silu'] for x in e],product=products,nonlinear_sat=[x['saturated'] for x in e],
            q=q,s=s,clips=clips,sats=sats,absmax=absmax,wd=packed(wd),sd=flatten(sd),y=y,
            pd=flatten([flatten(row) for row in pd]),
            errors=dict(product_vs_float=error_metrics([x/65536 for x in products],idealp),
                        final_vs_float=error_metrics([x/65536 for x in y],idealy))))
    return cases

def main():
    p=argparse.ArgumentParser();p.add_argument('--emit-lut',action='store_true')
    p.add_argument('--out',type=Path,default=ROOT/'build/ffn_vectors');args=p.parse_args()
    lutpath=ROOT/'rtl/vector/silu_sigmoid_lut.sv'
    if args.emit_lut: lutpath.write_text(lut_source(),encoding='ascii')
    assert lutpath.read_text(encoding='ascii') == lut_source(), 'LUT source differs from mathematical reference'
    args.out.mkdir(parents=True,exist_ok=True)
    max_error=0
    for t in range(-8*65536,8*65536+1,16):
        max_error=max(max_error,abs(element(t,65536)['silu']/65536-exact_silu(t/65536)))
    # Threshold includes intentional |x|>=8 truncation (max 8*sigmoid(-8)).
    assert max_error < 0.00270, max_error
    unit=unit_cases();tokens=[len(unit)]
    for c in unit: tokens += [c[k] for k in ('gate','up','silu','product','saturated')]
    (args.out/'unit.txt').write_text('\n'.join(map(str,tokens))+'\n',encoding='ascii')
    metadata=dict(seed=20261014,unit_cases=len(unit),silu_grid_checks=65537,
                  max_silu_abs_error=max_error,silu_abs_error_limit=0.00270,groups={})
    for group in (32,12):
        cases=ffn_cases(group);tokens=[len(cases)]
        for c in cases:
            if c['kind']=='normal':
                assert c['errors']['product_vs_float']['relative_l2'] < 0.0002
                assert c['errors']['final_vs_float']['relative_l2'] < 0.02
            if c['kind']=='zero':
                assert c['errors']['product_vs_float']['max_abs']==0 and c['errors']['final_vs_float']['max_abs']==0
            tokens += [c[k] for k in ('id','m','k','h','n','ng1','ng2')]
            for key in ('a','wg','wu','sx','sg','su','gate','up','pg','pu','silu','product','nonlinear_sat',
                        'q','s','clips','sats','absmax','wd','sd','y','pd'): tokens+=c[key]
        (args.out/f'ffn{group}.txt').write_text('\n'.join(map(str,tokens))+'\n',encoding='ascii')
        (args.out/f'ffn{group}.json').write_text(json.dumps(cases,indent=2)+'\n',encoding='utf8')
        metadata['groups'][str(group)]=dict(cases=len(cases),intermediate=sum(c['m']*c['h'] for c in cases))
    metadata['normal_product_relative_l2_limit']=0.0002
    metadata['normal_final_relative_l2_limit']=0.02
    (args.out/'reference_checks.json').write_text(json.dumps(metadata,indent=2)+'\n',encoding='utf8')
    print('FFN_MODEL_PASS',json.dumps(metadata))

if __name__=='__main__':main()
